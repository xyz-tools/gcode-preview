test('a Slic3r file carrying WIDTH comments is still detected as Slic3r', () => {
  // Slic3r's verbose gcode emits the same ;WIDTH:/;HEIGHT: comments as the
  // PrusaSlicer family it fathered. The PrusaFamily parser is tried first, so
  // treating those comments as an identification pattern claimed the file
  // before the Slic3r parser was ever consulted, losing its layer markers.
  const commands = [
    createCommand('; generated by Slic3r 1.3.0 on 2023-01-01', 'generated by Slic3r 1.3.0 on 2023-01-01'),
    createCommand('; move to next layer (1)', 'move to next layer (1)'),
    createCommand(';WIDTH:0.45', 'WIDTH:0.45'),
    createCommand(';HEIGHT:0.2', 'HEIGHT:0.2')
  ];

  expect(detectSlicer(commands)?.slicerName).toBe('Slic3r');
});

describe('Quint spec trace replay', () => {
  // Replays ITF traces produced from verification/quint/slicer-detector.qnt
  // against the real streaming pipeline: each trace step observes one line,
  // fed to a single Parser as its own chunk, and the detection latch is
  // compared after every line. Every compared field is a string or an
  // integer, so no float epsilon is needed.
  const tracesDir = join(process.cwd(), 'verification', 'quint', 'traces', 'slicer-detector');

  // An ITF value: strings are plain JSON; integers arrive either as plain
  // numbers or in Apalache's { "#bigint": "123" } wrapping.
  type ItfValue = boolean | string | number | { '#bigint': string } | undefined;
  type ItfState = Record<string, ItfValue>;

  const itfInt = (value: ItfValue, key: string): number => {
    if (typeof value === 'number') return value;
    if (typeof value === 'object' && value !== null && typeof value['#bigint'] === 'string') {
      return Number(value['#bigint']);
    }
    throw new Error(`expected an ITF integer for "${key}", got ${JSON.stringify(value)}`);
  };
  const itfStr = (value: ItfValue, key: string): string => {
    if (typeof value !== 'string') throw new Error(`expected a string for "${key}", got ${JSON.stringify(value)}`);
    return value;
  };

  // The spec's trace-contract variables, decoded; keys starting with '#'
  // (like '#meta') and the spec-internal history variables (firstFamily,
  // firstDetected) are never read and are thereby ignored.
  type SpecState = {
    cmd: string;
    family: string;
    detected: string;
    latchLine: number;
    linesSeen: number;
  };

  const decodeState = (raw: ItfState): SpecState => ({
    cmd: itfStr(raw.cmd, 'cmd'),
    family: itfStr(raw.family, 'family'),
    detected: itfStr(raw.detected, 'detected'),
    latchLine: itfInt(raw.latchLine, 'latchLine'),
    linesSeen: itfInt(raw.linesSeen, 'linesSeen')
  });

  // The line of G-code each spec event observes, mirroring the real
  // identificationPatterns in src/parser/*-parser.ts. An event missing from
  // this table fails the replay rather than being skipped.
  const eventLines: Record<string, string> = {
    prusa_header: '; generated by PrusaSlicer 2.9.2',
    prusa_layer_change: ';LAYER_CHANGE',
    simplify3d_header: '; Generated by Simplify3D',
    simplify3d_layer: '; layer 1, Z = 0.300',
    slic3r_header: '; generated by Slic3r 1.3.0 on 2023-01-01',
    slic3r_layer: '; move to next layer (1)',
    cura_header: ';Generated with Cura_SteamEngine 5.0',
    cura_layer: ';LAYER:0',
    neutral_comment: '; just a boring comment',
    neutral_move: 'G1 X10 Y5'
  };

  // The latched parser is private to Parser, so the replay reads it
  // structurally to compare the latched family alongside the public
  // metadata.slicerName.
  const latchedFamily = (parser: Parser): string =>
    (parser as unknown as { metadataParser: SlicerMetadataParser | null }).metadataParser?.slicerName ?? 'none';

  // The full per-step comparison from the trace contract. Every assertion
  // message names the trace file, step index, input line, field, and the
  // expected vs actual values.
  const compareStep = (
    traceFile: string,
    stepIndex: number,
    line: string,
    parser: Parser,
    realLatchLine: number,
    spec: SpecState
  ): void => {
    const at = (field: string, expected: unknown, actual: unknown) =>
      `${traceFile} step ${stepIndex} (${line}) field ${field}: expected ${String(expected)}, actual ${String(actual)}`;

    const family = latchedFamily(parser);
    expect(family, at('family', spec.family, family)).toBe(spec.family);
    const detected = parser.metadata.slicerName ?? 'none';
    expect(detected, at('detected', spec.detected, detected)).toBe(spec.detected);
    expect(parser.lineCount, at('linesSeen', spec.linesSeen, parser.lineCount)).toBe(spec.linesSeen);
    expect(realLatchLine, at('latchLine', spec.latchLine, realLatchLine)).toBe(spec.latchLine);
  };

  let traceFiles: string[] = [];
  try {
    traceFiles = readdirSync(tracesDir)
      .filter((file) => file.endsWith('.itf.json'))
      .sort();
  } catch {
    // Missing directory: the guard test below fails with a clear message.
  }

  test('the traces directory exists and holds at least one ITF trace', () => {
    // Fails (rather than silently skipping the replay) when the Quint traces
    // have not been generated into verification/quint/traces.
    expect(traceFiles.length, `expected *.itf.json traces in ${tracesDir}`).toBeGreaterThan(0);
  });

  for (const traceFile of traceFiles) {
    test(`replays ${traceFile} through the streaming detection latch`, () => {
      const parsed = JSON.parse(readFileSync(join(tracesDir, traceFile), 'utf8')) as { states: ItfState[] };
      expect(Array.isArray(parsed.states), `${traceFile}: ITF file has no states array`).toBe(true);
      expect(parsed.states.length, `${traceFile}: trace has no states`).toBeGreaterThan(0);
      const states = parsed.states.map(decodeState);

      // One Parser per trace: the latch persists across the steps, each of
      // which feeds exactly one line as its own streaming chunk.
      const parser = new Parser();
      let realLatchLine = -1;

      expect(states[0].cmd, `${traceFile} step 0: the first state must be the init state`).toBe('init');
      compareStep(traceFile, 0, '<init>', parser, realLatchLine, states[0]);

      for (let step = 1; step < states.length; step++) {
        const spec = states[step];
        const line = eventLines[spec.cmd];
        expect(line, `${traceFile} step ${step}: unknown event "${spec.cmd}" has no line in eventLines`).toBeDefined();
        parser.parseGCode(line);
        if (realLatchLine === -1 && latchedFamily(parser) !== 'none') {
          // the line just fed carries the 0-based index step - 1
          realLatchLine = step - 1;
        }
        compareStep(traceFile, step, line, parser, realLatchLine, spec);
      }
    });
  }
});

describe('slicer-detector v2 spec trace replay', () => {
  // Replays ITF traces produced from verification/quint-v2/slicer-detector.qnt
  // against the real streaming detection latch. Each trace state holds two
  // records; this replay decodes `ev` alone: the chunk the step fed (kind,
  // line tags, filler count) plus the spec's projection of the latch after
  // the step (family, detected, latchStart, linesSeen). The sum-typed truth
  // and the ghost fields live in `s`, which the spec's own invariants own and
  // this replay deliberately never decodes. Every compared value is a string
  // or an integer, compared exactly — nothing is scaled, no epsilon anywhere.
  const tracesDir = join(process.cwd(), 'verification', 'quint-v2', 'traces', 'slicer-detector');

  // The event-to-line mapping, promoted into the contract: per line tag a SET
  // of representative G-code lines, including the case and boundary variants
  // the spec's matchedFamilies table pins. Within one tag every representative
  // matches exactly the same parser families and carries the same generator
  // literal, so they are interchangeable step inputs; the replay proves that
  // by running every trace once per representative column (pass r uses
  // representative r mod set size), and the contract test below re-checks
  // each string one by one.
  const REPRESENTATIVES: Record<string, string[]> = {
    prusa_header: [
      '; generated by PrusaSlicer 2.9.2',
      ';generated by PrusaSlicer 2.7.0+win64',
      '; GENERATED BY PrusaSlicer 2.9.2'
    ],
    prusa_layer_change: [';LAYER_CHANGE', '; LAYER_CHANGE', ';BEFORE_LAYER_CHANGE'],
    simplify3d_header: ['; Generated by Simplify3D', ';Simplify3D(R) Version 4.1.2', '; generated by simplify3d'],
    simplify3d_layer: ['; layer 1, Z = 0.300', ';LAYER 12, Z = 24.100', '; layer 2, Z = -0.100'],
    slic3r_header: ['; generated by Slic3r 1.3.0 on 2023-01-01', ';Generated by Slic3r 1.2.9', '; Slic3r PE 1.41.2'],
    slic3r_layer: ['; move to next layer (1)', ';Move To Next Layer (42)', '; layer_z = 0.350'],
    cura_header: [
      ';Generated with Cura_SteamEngine 5.0',
      '; generated with cura_steamengine 4.13.1',
      ';CURA_PROFILE_STRING'
    ],
    cura_layer: [';LAYER:0', ';LAYER:250', ';LAYER:7 '],
    neutral_comment: ['; just a boring comment', ';TIME:1234', '; Layer count'],
    neutral_move: ['G1 X10 Y5', 'G1 X10 Y5 E0.3 F1800', 'M104 S200'],
    ambig_prusa_s3d: ['; sliced with PrusaSlicer, Layer count: 25', ';PrusaSlicer profile exported from Simplify3D'],
    ambig_s3d_slic3r: [
      '; Generated by Slic3r 1.3.0 with a Simplify3D profile',
      ';Simplify3D remix of Slic3r 1.2.9 output'
    ],
    ambig_slic3r_cura: [';LAYER:4 exported by Slic3r 1.2.9', ';LAYER:0 from Slic3r PE 1.41.0']
  };

  // The neutral comment line window floods are padded with (ev.fill copies
  // precede the marker line). Neutral like neutral_comment: it must match no
  // identification pattern, which the contract test verifies.
  const FILLER = '; filler comment line for the detection window';

  // What a fresh parse latches when a tag's line arrives first and alone:
  // the priority-resolved family and the name the latching chunk yields.
  // Mirrors the spec's matchedFamilies/firstByPriority/resolveName pipeline,
  // so a pattern edit that changes any representative's matched set fails
  // here even if no random trace happens to lead with that tag.
  const SINGLE_LINE_OUTCOME: Record<string, { family: string; detected: string }> = {
    prusa_header: { family: 'PrusaFamily', detected: 'PrusaSlicer' },
    prusa_layer_change: { family: 'PrusaFamily', detected: 'PrusaFamily' },
    simplify3d_header: { family: 'Simplify3D', detected: 'Simplify3D' },
    simplify3d_layer: { family: 'Simplify3D', detected: 'Simplify3D' },
    slic3r_header: { family: 'Slic3r', detected: 'Slic3r' },
    slic3r_layer: { family: 'Slic3r', detected: 'Slic3r' },
    cura_header: { family: 'Cura', detected: 'Cura' },
    cura_layer: { family: 'Cura', detected: 'Cura' },
    neutral_comment: { family: 'none', detected: 'none' },
    neutral_move: { family: 'none', detected: 'none' },
    ambig_prusa_s3d: { family: 'PrusaFamily', detected: 'PrusaSlicer' },
    ambig_s3d_slic3r: { family: 'Simplify3D', detected: 'Simplify3D' },
    ambig_slic3r_cura: { family: 'Slic3r', detected: 'Slic3r' }
  };

  // The spec's trace contract, decoded from `ev` only.
  type V2Step = {
    kind: string;
    line1: string;
    line2: string;
    fill: number;
    family: string;
    detected: string;
    latchStart: number;
    linesSeen: number;
  };

  const decodeStep = (raw: ItfState): V2Step => {
    const ev = itfRecord(raw.ev, 'ev');
    return {
      kind: itfStr(ev.kind, 'ev.kind'),
      line1: itfStr(ev.line1, 'ev.line1'),
      line2: itfStr(ev.line2, 'ev.line2'),
      fill: itfInt(ev.fill, 'ev.fill'),
      family: itfStr(ev.family, 'ev.family'),
      detected: itfStr(ev.detected, 'ev.detected'),
      latchStart: itfInt(ev.latchStart, 'ev.latchStart'),
      linesSeen: itfInt(ev.linesSeen, 'ev.linesSeen')
    };
  };

  // The latched parser is private to Parser, so the replay reads it
  // structurally to compare the latched family alongside the public
  // metadata.slicerName (recorded as an open item in the companion).
  const latchedFamily = (parser: Parser): string =>
    (parser as unknown as { metadataParser: SlicerMetadataParser | null }).metadataParser?.slicerName ?? 'none';

  /** The representative for a line tag on a given pass; unknown tags fail. */
  const representative = (tag: string, pass: number, context: string): string => {
    const reps = REPRESENTATIVES[tag];
    if (!reps) throw new Error(`${context}: unknown line tag "${tag}" has no representatives`);
    return reps[pass % reps.length];
  };

  /** The chunk a step describes: ev.fill neutral fillers, then the tagged
   * line(s), joined with newlines into the single string fed to the parser. */
  const chunkLines = (spec: V2Step, pass: number, context: string): string[] => {
    const lines: string[] = new Array<string>(spec.fill).fill(FILLER);
    if (spec.line1 !== '') lines.push(representative(spec.line1, pass, context));
    if (spec.line2 !== '') lines.push(representative(spec.line2, pass, context));
    return lines;
  };

  const maxReps = Math.max(...Object.values(REPRESENTATIVES).map((reps) => reps.length));

  const traceFiles = listTraceFiles(tracesDir);

  test('the v2 traces directory exists and holds at least one ITF trace', () => {
    // Fails (rather than silently skipping the replay) when the Quint traces
    // have not been generated into verification/quint-v2/traces/slicer-detector.
    expect(traceFiles.length, `expected *.itf.json traces in ${tracesDir}`).toBeGreaterThan(0);
  });

  test('every representative line resolves to its pinned family and name when fed first', () => {
    // The per-string half of the contract: each representative, fed alone to
    // a fresh parse, latches exactly the family and name the spec's line
    // table resolves for its tag — so pattern overlaps asserted by the spec
    // (the ambiguous lines) and non-matches (the neutral lines, the filler)
    // are pinned string by string and cannot silently rot.
    for (const [tag, outcome] of Object.entries(SINGLE_LINE_OUTCOME)) {
      for (const line of REPRESENTATIVES[tag]) {
        const parser = new Parser();
        parser.parseGCode(line);
        const family = latchedFamily(parser);
        const detected = parser.metadata.slicerName ?? 'none';
        expect(family, `${tag} (${line}) family: expected ${outcome.family}, actual ${family}`).toBe(outcome.family);
        expect(detected, `${tag} (${line}) detected: expected ${outcome.detected}, actual ${detected}`).toBe(
          outcome.detected
        );
      }
    }
    const parser = new Parser();
    parser.parseGCode(FILLER);
    expect(latchedFamily(parser), `filler (${FILLER}) must match no slicer fingerprint`).toBe('none');
  });

  for (const traceFile of traceFiles) {
    test(`replays ${traceFile} through the streaming detection latch`, () => {
      const steps = readTrace(tracesDir, traceFile).map(decodeStep);

      expect(steps[0].kind, `${traceFile} step 0: the first state must be the init state`).toBe('init');
      expect(steps[0].family, `${traceFile} step 0: nothing may be latched yet`).toBe('none');
      expect(steps[0].linesSeen, `${traceFile} step 0: no lines may be counted yet`).toBe(0);

      // One pass per representative column: pass r rebuilds every chunk from
      // each tag's representative r mod set size, so the whole set is
      // exercised against every trace while the spec outcome stays the same.
      for (let pass = 0; pass < maxReps; pass++) {
        // One Parser per pass: the latch persists across the trace's steps.
        const parser = new Parser();
        let realLatchStart = -1;

        for (let step = 1; step < steps.length; step++) {
          const spec = steps[step];
          const context = `${traceFile} pass ${pass} step ${step}`;
          const lines = chunkLines(spec, pass, context);
          expect(lines.length, `${context}: event "${spec.kind}" described an empty chunk`).toBeGreaterThan(0);

          const before = parser.lineCount;
          const wasLatched = latchedFamily(parser) !== 'none';
          parser.parseGCode(lines.join('\n'));
          if (!wasLatched && latchedFamily(parser) !== 'none') {
            // The latch flipped on this chunk: its first line carries the
            // 0-based index the parser had counted before the chunk was fed.
            realLatchStart = before;
          }

          const at = (field: string, expected: unknown, actual: unknown): string =>
            `${context} (${spec.kind}: ${spec.line1}${spec.line2 ? ' + ' + spec.line2 : ''}` +
            `${spec.fill > 0 ? ` after ${spec.fill} fillers` : ''}) field ${field}: ` +
            `expected ${String(expected)}, actual ${String(actual)}`;

          const family = latchedFamily(parser);
          expect(family, at('family', spec.family, family)).toBe(spec.family);
          const detected = parser.metadata.slicerName ?? 'none';
          expect(detected, at('detected', spec.detected, detected)).toBe(spec.detected);
          expect(parser.lineCount, at('linesSeen', spec.linesSeen, parser.lineCount)).toBe(spec.linesSeen);
          expect(realLatchStart, at('latchStart', spec.latchStart, realLatchStart)).toBe(spec.latchStart);
        }
      }
    });
  }
});
