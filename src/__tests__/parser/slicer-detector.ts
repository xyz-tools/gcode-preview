test('a Slic3r file carrying WIDTH comments is still detected as Slic3r', () => {
  // Slic3r's verbose gcode emits the same ;WIDTH:/;HEIGHT: comments as the
  // PrusaSlicer family it fathered. The PrusaFamily parser is tried first, so
  // treating those comments as an identification pattern claimed the file
  // before the Slic3r parser was ever consulted, losing its layer markers.
  const commands = [
    createCommand('; generated by Slic3r 1.3.0 on 2023-01-01', 'generated by Slic3r 1.3.0 on 2023-01-01'),
    createCommand('; move to next layer (1)', 'move to next layer (1)'),
    createCommand(';WIDTH:0.45', 'WIDTH:0.45'),
    createCommand(';HEIGHT:0.2', 'HEIGHT:0.2')
  ];

  expect(detectSlicer(commands)?.slicerName).toBe('Slic3r');
});

describe('Quint spec trace replay', () => {
  // Replays ITF traces produced from verification/quint/slicer-detector.qnt
  // against the real streaming pipeline: each trace step observes one line,
  // fed to a single Parser as its own chunk, and the detection latch is
  // compared after every line. Every compared field is a string or an
  // integer, so no float epsilon is needed.
  const tracesDir = join(process.cwd(), 'verification', 'quint', 'traces', 'slicer-detector');

  // An ITF value: strings are plain JSON; integers arrive either as plain
  // numbers or in Apalache's { "#bigint": "123" } wrapping.
  type ItfValue = boolean | string | number | { '#bigint': string } | undefined;
  type ItfState = Record<string, ItfValue>;

  const itfInt = (value: ItfValue, key: string): number => {
    if (typeof value === 'number') return value;
    if (typeof value === 'object' && value !== null && typeof value['#bigint'] === 'string') {
      return Number(value['#bigint']);
    }
    throw new Error(`expected an ITF integer for "${key}", got ${JSON.stringify(value)}`);
  };
  const itfStr = (value: ItfValue, key: string): string => {
    if (typeof value !== 'string') throw new Error(`expected a string for "${key}", got ${JSON.stringify(value)}`);
    return value;
  };

  // The spec's trace-contract variables, decoded; keys starting with '#'
  // (like '#meta') and the spec-internal history variables (firstFamily,
  // firstDetected) are never read and are thereby ignored.
  type SpecState = {
    cmd: string;
    family: string;
    detected: string;
    latchLine: number;
    linesSeen: number;
  };

  const decodeState = (raw: ItfState): SpecState => ({
    cmd: itfStr(raw.cmd, 'cmd'),
    family: itfStr(raw.family, 'family'),
    detected: itfStr(raw.detected, 'detected'),
    latchLine: itfInt(raw.latchLine, 'latchLine'),
    linesSeen: itfInt(raw.linesSeen, 'linesSeen')
  });

  // The line of G-code each spec event observes, mirroring the real
  // identificationPatterns in src/parser/*-parser.ts. An event missing from
  // this table fails the replay rather than being skipped.
  const eventLines: Record<string, string> = {
    prusa_header: '; generated by PrusaSlicer 2.9.2',
    prusa_layer_change: ';LAYER_CHANGE',
    simplify3d_header: '; Generated by Simplify3D',
    simplify3d_layer: '; layer 1, Z = 0.300',
    slic3r_header: '; generated by Slic3r 1.3.0 on 2023-01-01',
    slic3r_layer: '; move to next layer (1)',
    cura_header: ';Generated with Cura_SteamEngine 5.0',
    cura_layer: ';LAYER:0',
    neutral_comment: '; just a boring comment',
    neutral_move: 'G1 X10 Y5'
  };

  // The latched parser is private to Parser, so the replay reads it
  // structurally to compare the latched family alongside the public
  // metadata.slicerName.
  const latchedFamily = (parser: Parser): string =>
    (parser as unknown as { metadataParser: SlicerMetadataParser | null }).metadataParser?.slicerName ?? 'none';

  // The full per-step comparison from the trace contract. Every assertion
  // message names the trace file, step index, input line, field, and the
  // expected vs actual values.
  const compareStep = (
    traceFile: string,
    stepIndex: number,
    line: string,
    parser: Parser,
    realLatchLine: number,
    spec: SpecState
  ): void => {
    const at = (field: string, expected: unknown, actual: unknown) =>
      `${traceFile} step ${stepIndex} (${line}) field ${field}: expected ${String(expected)}, actual ${String(actual)}`;

    const family = latchedFamily(parser);
    expect(family, at('family', spec.family, family)).toBe(spec.family);
    const detected = parser.metadata.slicerName ?? 'none';
    expect(detected, at('detected', spec.detected, detected)).toBe(spec.detected);
    expect(parser.lineCount, at('linesSeen', spec.linesSeen, parser.lineCount)).toBe(spec.linesSeen);
    expect(realLatchLine, at('latchLine', spec.latchLine, realLatchLine)).toBe(spec.latchLine);
  };

  let traceFiles: string[] = [];
  try {
    traceFiles = readdirSync(tracesDir)
      .filter((file) => file.endsWith('.itf.json'))
      .sort();
  } catch {
    // Missing directory: the guard test below fails with a clear message.
  }

  test('the traces directory exists and holds at least one ITF trace', () => {
    // Fails (rather than silently skipping the replay) when the Quint traces
    // have not been generated into verification/quint/traces.
    expect(traceFiles.length, `expected *.itf.json traces in ${tracesDir}`).toBeGreaterThan(0);
  });

  for (const traceFile of traceFiles) {
    test(`replays ${traceFile} through the streaming detection latch`, () => {
      const parsed = JSON.parse(readFileSync(join(tracesDir, traceFile), 'utf8')) as { states: ItfState[] };
      expect(Array.isArray(parsed.states), `${traceFile}: ITF file has no states array`).toBe(true);
      expect(parsed.states.length, `${traceFile}: trace has no states`).toBeGreaterThan(0);
      const states = parsed.states.map(decodeState);

      // One Parser per trace: the latch persists across the steps, each of
      // which feeds exactly one line as its own streaming chunk.
      const parser = new Parser();
      let realLatchLine = -1;

      expect(states[0].cmd, `${traceFile} step 0: the first state must be the init state`).toBe('init');
      compareStep(traceFile, 0, '<init>', parser, realLatchLine, states[0]);

      for (let step = 1; step < states.length; step++) {
        const spec = states[step];
        const line = eventLines[spec.cmd];
        expect(line, `${traceFile} step ${step}: unknown event "${spec.cmd}" has no line in eventLines`).toBeDefined();
        parser.parseGCode(line);
        if (realLatchLine === -1 && latchedFamily(parser) !== 'none') {
          // the line just fed carries the 0-based index step - 1
          realLatchLine = step - 1;
        }
        compareStep(traceFile, step, line, parser, realLatchLine, spec);
      }
    });
  }
});
