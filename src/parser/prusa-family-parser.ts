import { GCodeCommand } from './gcode-parser';
import { SlicerMetadataParser, LayerMetadata, ExtrusionDimensionMetadata } from './metadata-parser-base';

/**
 * Parser for the PrusaSlicer comment dialect, shared by the whole family of
 * PrusaSlicer-derived slicers (SuperSlicer, OrcaSlicer, BambuStudio).
 *
 * Layer comment format:
 * ;LAYER_CHANGE
 * ;Z:0.3
 * ;HEIGHT:0.3
 *
 * Bambu/Orca additionally emit explicit layer indices:
 * ;LAYER:12
 *
 * Extrusion dimension comments, announcing the width and height of the
 * extrusions that follow (many per layer):
 * ;WIDTH:0.45
 * ;HEIGHT:0.16
 */
export class PrusaFamilyMetadataParser extends SlicerMetadataParser {
  readonly slicerName = 'PrusaFamily';

  /** Generator names reported verbatim when found in the header comments */
  private static readonly KNOWN_SLICERS = ['PrusaSlicer', 'SuperSlicer', 'OrcaSlicer', 'BambuStudio'];

  /**
   * Matches the standalone dimension comments (`WIDTH:0.45`, `HEIGHT:0.16`;
   * the parser hands comments over pre-trimmed and without the `;`).
   * Whitespace around the colon and value is tolerated, but the value must be
   * a plain decimal number — trailing junk (`0.45mm`) rejects the line rather
   * than being silently truncated by parseFloat. `\d+(?:\.\d+)?` is written
   * without adjacent ambiguous digit runs on purpose: `\d*\.?\d+` backtracks
   * polynomially on long digit strings with a non-matching tail
   * (js/polynomial-redos), this form fails in linear time.
   */
  private static readonly DIMENSION_PATTERN = /^(WIDTH|HEIGHT)\s*:\s*(\d+(?:\.\d+)?)\s*$/;

  readonly identificationPatterns = [
    /generated by PrusaSlicer/i,
    /generated by SuperSlicer/i,
    /generated by OrcaSlicer/i,
    /generated by BambuStudio/i,
    /LAYER_CHANGE/,
    /BEFORE_LAYER_CHANGE/,
    /AFTER_LAYER_CHANGE/,
    /^WIDTH:/,
    /^HEIGHT:/,
    /PrusaSlicer/i,
    /SuperSlicer/i,
    /OrcaSlicer/i,
    /BambuStudio/i,
    /Bambu Lab/i
  ];

  /**
   * Reports the specific family member named in the header comments, falling
   * back to the generic family name when only the shared LAYER_CHANGE dialect
   * identified the file.
   * @param commentCommands - Array of gcode commands with comments
   * @returns The specific slicer name, or 'PrusaFamily' when unknown
   */
  detectSlicerName(commentCommands: GCodeCommand[]): string {
    const sample = commentCommands.length > 200 ? commentCommands.slice(0, 200) : commentCommands;
    for (const name of PrusaFamilyMetadataParser.KNOWN_SLICERS) {
      if (sample.some((cmd) => cmd.comment!.includes(name))) {
        return name;
      }
    }
    return this.slicerName;
  }

  parseLayerMetadata(commands: GCodeCommand[]): LayerMetadata[] {
    const layers: LayerMetadata[] = [];
    let currentZ: number | undefined;
    let currentHeight: number | undefined;
    let currentLineIndex = -1;
    let currentExplicitLayerIndex: number | undefined;
    let autoLayerIndex = 0;
    let inLayerChange = false;

    const pushCurrentLayer = (): void => {
      if (currentLineIndex < 0) return;
      layers.push({
        layerIndex: currentExplicitLayerIndex ?? autoLayerIndex,
        z: currentZ,
        height: currentHeight,
        lineIndex: currentLineIndex
      });
      autoLayerIndex++;
    };

    for (let i = 0; i < commands.length; i++) {
      const comment = commands[i].comment;
      if (!comment) continue;

      if (
        comment.includes('LAYER_CHANGE') &&
        !comment.includes('BEFORE_LAYER_CHANGE') &&
        !comment.includes('AFTER_LAYER_CHANGE')
      ) {
        pushCurrentLayer();
        currentLineIndex = i;
        currentZ = undefined;
        currentHeight = undefined;
        currentExplicitLayerIndex = undefined;
        inLayerChange = true;
        continue;
      }

      if (!inLayerChange) continue;

      if (comment.startsWith('Z:')) {
        const val = parseFloat(comment.slice(2));
        if (!isNaN(val)) currentZ = val;
        continue;
      }

      if (comment.startsWith('HEIGHT:')) {
        const val = parseFloat(comment.slice(7));
        if (!isNaN(val)) currentHeight = val;
        continue;
      }

      const layerMatch = comment.match(/^LAYER:(\d+)/);
      if (layerMatch) {
        currentExplicitLayerIndex = parseInt(layerMatch[1]);
      }
    }

    pushCurrentLayer();
    return layers;
  }

  /**
   * Parses `;WIDTH:` / `;HEIGHT:` extrusion dimension comments
   * @param commands - Array of gcode commands with comments
   * @returns One event per dimension comment, in line order
   * @remarks
   * Every `HEIGHT:` line is reported, including the ones inside a
   * `LAYER_CHANGE` block: there it doubles as the layer's height (see
   * parseLayerMetadata) and as the line height of the paths that follow,
   * which is exactly how adaptive layer height reaches individual paths.
   * Non-numeric and non-positive values are ignored.
   */
  parseExtrusionDimensions(commands: GCodeCommand[]): ExtrusionDimensionMetadata[] {
    const dimensions: ExtrusionDimensionMetadata[] = [];

    for (let i = 0; i < commands.length; i++) {
      const comment = commands[i].comment;
      if (!comment) continue;

      const match = PrusaFamilyMetadataParser.DIMENSION_PATTERN.exec(comment);
      if (!match) continue;

      const value = parseFloat(match[2]);
      if (!Number.isFinite(value) || value <= 0) continue;

      if (match[1] === 'WIDTH') {
        dimensions.push({ width: value, lineIndex: i });
      } else {
        dimensions.push({ height: value, lineIndex: i });
      }
    }

    return dimensions;
  }
}
